/**
 * Lightweight i18n system for the dashboard.
 * Usage: const { t, lang, setLang } = useLang();
 *        t("sidebar.overview") → "Tổng quan" or "Overview"
 */

import { useCallback, useEffect, useState } from "react";

export type Lang = "en" | "vi";

const STORAGE_KEY = "gateway.lang";

let currentLang: Lang = (typeof window !== "undefined"
  ? (window.localStorage.getItem(STORAGE_KEY) as Lang) ?? "en"
  : "en");

const listeners = new Set<() => void>();

export function getLang(): Lang {
  return currentLang;
}

export function setLangGlobal(lang: Lang) {
  currentLang = lang;
  if (typeof window !== "undefined") {
    window.localStorage.setItem(STORAGE_KEY, lang);
  }
  listeners.forEach((fn) => fn());
}

export function useLang() {
  const [, rerender] = useState(0);

  useEffect(() => {
    const fn = () => rerender((n) => n + 1);
    listeners.add(fn);
    return () => { listeners.delete(fn); };
  }, []);

  const t = useCallback((key: string): string => {
    return translations[currentLang]?.[key] ?? translations.en[key] ?? key;
  }, []);

  return { t, lang: currentLang, setLang: setLangGlobal };
}

